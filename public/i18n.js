window.PetloxtusI18n = {
  LANG_KEY: "petloxtus_lang_v1",
  currentLang: "en",

  detectPreferredLanguage() {
    const saved = localStorage.getItem(this.LANG_KEY);
    if (saved && PETLOXTUS_TRANSLATIONS[saved]) return saved;
    const navLang = (navigator.language || "en").toLowerCase();
    const short = navLang.split("-")[0];
    if (PETLOXTUS_TRANSLATIONS[short]) return short;
    return "en";
  },

  t(key, fallback) {
    const dict = PETLOXTUS_TRANSLATIONS[this.currentLang] || PETLOXTUS_TRANSLATIONS.en;
    return dict[key] || PETLOXTUS_TRANSLATIONS.en[key] || fallback || "";
  },

  applyLanguage(lang) {
    const valid = PETLOXTUS_TRANSLATIONS[lang] ? lang : "en";
    this.currentLang = valid;
    localStorage.setItem(this.LANG_KEY, valid);
    document.documentElement.lang = valid;

    document.querySelectorAll(".js-lang-switcher").forEach((sel) => {
      if (sel.value !== valid) sel.value = valid;
    });

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = this.t(key);
      if (val) el.textContent = val;
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      const val = this.t(key);
      if (val) el.setAttribute("placeholder", val);
    });
  }
};
